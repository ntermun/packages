#!/usr/bin/env bash
# build-pkg.sh - pack an already installed file tree into a pacman package.
#
# This is the "fakeroot + makepkg --repackage" equivalent for the ntermun
# repository.  It does NOT compile anything: point it at a directory that
# looks like a filesystem root (e.g. containing usr/bin/bash) and it produces
# <name>-<ver>-<rel>-<arch>.pkg.tar.zst with a valid .PKGINFO and root:root
# ownership.  No .MTREE is generated (optional for pacman).
#
# Usage:
#   build-pkg.sh -n NAME -v VER [-r REL] [-a ARCH] [-d DESC] [-u URL] \
#                [-D "dep1,dep2"] -C PKGDIR [-o OUTDIR]
#   build-pkg.sh NAME VER [REL] PKGDIR [OUTDIR]     # positional form
#
# Environment:
#   ZSTD_LEVEL   compression level (default 19)
set -euo pipefail

PROG=${0##*/}

die() { printf '%s: error: %s\n' "$PROG" "$*" >&2; exit 1; }
warn() { printf '%s: warning: %s\n' "$PROG" "$*" >&2; }

usage() {
	cat <<EOF
Usage: $PROG -n NAME -v VER [-r REL] [-a ARCH] [-d DESC] [-u URL]
              [-D "dep1,dep2"] -C PKGDIR [-o OUTDIR]

  -n NAME    package name (required)
  -v VER     package version, without pkgrel (required)
  -r REL     pkgrel, default 1
  -a ARCH    architecture, default aarch64
  -d DESC    one-line description
  -u URL     upstream URL
  -D DEPS    comma/space separated runtime dependencies (repeatable)
  -C DIR     prepared file tree (the future /)
  -o DIR     output directory, default: <repo>/out/<arch>
  -h         this help
EOF
}

pkgname=
pkgver=
pkgrel=1
arch=aarch64
desc=
url=
pkgdir=
outdir=
deps_raw=()

while getopts ":n:v:r:a:d:u:D:C:o:h" opt; do
	case $opt in
		n) pkgname=$OPTARG ;;
		v) pkgver=$OPTARG ;;
		r) pkgrel=$OPTARG ;;
		a) arch=$OPTARG ;;
		d) desc=$OPTARG ;;
		u) url=$OPTARG ;;
		D) deps_raw+=("$OPTARG") ;;
		C) pkgdir=$OPTARG ;;
		o) outdir=$OPTARG ;;
		h) usage; exit 0 ;;
		:) die "option -$OPTARG requires an argument" ;;
		\?) die "unknown option -$OPTARG" ;;
	esac
done
shift $((OPTIND - 1))

# Positional compatibility: NAME VER [REL] PKGDIR [OUTDIR]
if [[ -z $pkgname && $# -ge 3 ]]; then
	pkgname=$1 pkgver=$2
	if [[ -d ${3:-} ]]; then
		pkgdir=$3
	else
		pkgrel=$3 pkgdir=${4:-} outdir=${5:-}
	fi
fi

[[ -n $pkgname ]] || die "package name is required (-n)"
[[ -n $pkgver ]] || die "package version is required (-v)"
[[ -n $pkgdir ]] || die "prepared tree is required (-C)"
[[ -d $pkgdir ]] || die "no such directory: $pkgdir"
pkgdir=$(cd "$pkgdir" && pwd -P)

script_dir=$(cd "$(dirname "$0")" && pwd -P)
outdir=${outdir:-$script_dir/out/$arch}
mkdir -p "$outdir"
outdir=$(cd "$outdir" && pwd -P)

name_re='^[a-z0-9@._+][a-z0-9@._+-]*$'
[[ $pkgname =~ $name_re ]] || die "invalid package name: $pkgname"
[[ $pkgver != *-* ]] || warn "pkgver contains '-', pacman may parse the filename oddly"
[[ $pkgver =~ ^[A-Za-z0-9._+~]+$ ]] || warn "pkgver has unusual characters: $pkgver"
[[ $pkgrel =~ ^[0-9]+(\.[0-9]+)?$ ]] || die "invalid pkgrel: $pkgrel"

# Keep metadata one-line and predictable.
desc=${desc//$'\n'/ }
url=${url//$'\n'/ }
fullver=$pkgver-$pkgrel

# Refuse to package an empty tree: it is almost always a broken build.
if [[ -z $(find "$pkgdir" -mindepth 1 -print -quit) ]]; then
	die "tree is empty: $pkgdir"
fi

# Anything left over from a previous packaging run must not leak into the
# payload; .PKGINFO/.MTREE/.INSTALL belong to metadata, not to the payload.
rm -f "$pkgdir/.PKGINFO" "$pkgdir/.MTREE" "$pkgdir/.INSTALL" "$pkgdir/.BUILDINFO"

# --- permissions -----------------------------------------------------------
# Directories 0755, executables 0755, everything else 0644.  Executables in
# bin/sbin/libexec are what matters most; normalising all of them keeps the
# package deterministic.
find "$pkgdir" -type d -exec chmod 0755 {} +
find "$pkgdir" -type f -perm -u+x -exec chmod 0755 {} +
find "$pkgdir" -type f ! -perm -u+x -exec chmod 0644 {} +

# --- installed size --------------------------------------------------------
# Sum of regular file sizes, in bytes.  GNU find is used when available;
# the stat fallback covers busybox-style userlands.
installed_size() {
	if find "$1" -type f -printf '' >/dev/null 2>&1; then
		find "$1" -type f -printf '%s\n' | awk '{s += $1} END {printf "%d\n", s}'
	else
		find "$1" -type f -print0 |
			xargs -0 -r stat -c %s 2>/dev/null |
			awk '{s += $1} END {printf "%d\n", s}'
	fi
}

isize=$(installed_size "$pkgdir")
[[ -n $isize ]] || isize=0

# --- .PKGINFO --------------------------------------------------------------
meta=$(mktemp -d "${TMPDIR:-/tmp}/build-pkg.XXXXXX")
trap 'rm -rf "$meta"' EXIT

{
	printf '# Generated by build-pkg.sh\n'
	printf 'pkgname = %s\n' "$pkgname"
	printf 'pkgbase = %s\n' "$pkgname"
	printf 'pkgver = %s\n' "$fullver"
	printf 'pkgdesc = %s\n' "$desc"
	printf 'url = %s\n' "$url"
	printf 'builddate = %s\n' "$(date +%s)"
	printf 'packager = ntermun repository builder\n'
	printf 'size = %s\n' "$isize"
	printf 'arch = %s\n' "$arch"
	# deps_raw may contain "a,b c"; normalise to one "depend = x" per line.
	if ((${#deps_raw[@]})); then
		printf '%s\n' "${deps_raw[@]}" |
			tr ', ' '\n\n' |
			sed '/^$/d' |
			while IFS= read -r dep; do
				printf 'depend = %s\n' "$dep"
			done
	fi
} >"$meta/.PKGINFO"
chmod 0644 "$meta/.PKGINFO"

# --- archive ---------------------------------------------------------------
tmp="$outdir/.$pkgname-$fullver-$arch.pkg.tar.zst.$$"
trap 'rm -rf "$meta"; rm -f "$tmp"' EXIT

level=${ZSTD_LEVEL:-19}

# - .PKGINFO comes first and lives at the archive root;
# - -C switches between the metadata dir and the payload tree;
# - numeric owner 0/0 makes the package root:root even without fakeroot.
tar --create \
	--owner=0 --group=0 --numeric-owner \
	--exclude='./.PKGINFO' --exclude='./.MTREE' \
	--exclude='./.INSTALL' --exclude='./.BUILDINFO' \
	-C "$meta" .PKGINFO \
	-C "$pkgdir" . |
	zstd -q -T0 "-$level" -o "$tmp"

zstd -tq "$tmp" || die "produced archive is corrupt"

out="$outdir/$pkgname-$fullver-$arch.pkg.tar.zst"
mv -f "$tmp" "$out"
trap 'rm -rf "$meta"' EXIT

printf 'built: %s\n' "$out"
printf '  pkgname=%s pkgver=%s arch=%s isize=%s\n' "$pkgname" "$fullver" "$arch" "$isize"
