#!/usr/bin/env bash
#
# ci-build.sh -- mini-makepkg for cross-compiled aarch64-linux-musl packages.
#
# pacman/makepkg are not available on the CI runner, so this script implements
# the small subset of makepkg that the PKGBUILDs in packages/ need:
#
#   1. source the PKGBUILD in a clean subshell (srcdir/pkgdir set),
#   2. download "source" entries into $srcdir and verify "sha256sums",
#   3. extract archives,
#   4. run prepare() / build() / check() / package(),
#   5. strip ELF files, generate .PKGINFO, call build-pkg.sh,
#   6. install the result into a shared staging prefix ($STAGE) so that
#      later packages (openssh -> openssl) can find headers and static libs.
#
# Usage:
#   ./ci-build.sh                 # build every package, in dependency order
#   ./ci-build.sh bash grep       # build only the named packages
#
# Environment:
#   TC=/path/to/aarch64-linux-musl-cross   toolchain root (bin/ inside)
#   CROSS=aarch64-linux-musl               toolchain triplet
#   JOBS=2                                 parallel make jobs
#   PKGDEST=out                            output directory
#   BUILDDIR=.build                        work directory
#   STAGE=.build/stage                     staging prefix
#   STRIP=no                               disable ELF stripping
#
set -euo pipefail
umask 022

ROOT=$(cd -- "$(dirname -- "$0")" && pwd)
PROG=${0##*/}

die()  { printf '%s: error: %s\n' "$PROG" "$*" >&2; exit 1; }
warn() { printf '%s: warning: %s\n' "$PROG" "$*" >&2; }
info() { printf '\n==> %s\n' "$*"; }

usage() {
	cat <<EOF
Usage: $PROG [pkgname...]

Build packages from packages/<pkgname>/PKGBUILD for aarch64-linux-musl.

  (no arguments)  build all packages in dependency order
  pkgname...      build only the listed packages

Environment: TC, CROSS, JOBS, PKGDEST, BUILDDIR, STAGE, STRIP
EOF
}

case ${1:-} in
	-h|--help) usage; exit 0 ;;
esac

PKGDEST=${PKGDEST:-$ROOT/out}
BUILDDIR=${BUILDDIR:-$ROOT/.build}
STAGE=${STAGE:-$BUILDDIR/stage}
JOBS=${JOBS:-$(nproc 2>/dev/null || echo 2)}
CROSS=${CROSS:-aarch64-linux-musl}
STRIP_MODE=${STRIP:-yes}

# Build order matters: openssh needs openssl in $STAGE.
DEFAULT_ORDER=(
	bash coreutils grep sed gawk tar gzip
	findutils diffutils make openssl openssh
)

if [[ $# -gt 0 ]]; then
	packages=("$@")
else
	packages=("${DEFAULT_ORDER[@]}")
fi

# --- toolchain -------------------------------------------------------------
if [[ -n ${TC:-} ]]; then
	export PATH="$TC/bin:$PATH"
fi
command -v "$CROSS-gcc" >/dev/null 2>&1 ||
	die "cross compiler '$CROSS-gcc' not found (set TC=/path/to/$CROSS-cross and retry)"

export CC=${CC:-$CROSS-gcc}
export CXX=${CXX:-$CROSS-g++}
export AR=${AR:-$CROSS-ar}
export RANLIB=${RANLIB:-$CROSS-ranlib}
export STRIP=${STRIP:-$CROSS-strip}
export NM=${NM:-$CROSS-nm}
export CFLAGS=${CFLAGS:--O2 -pipe}
export CXXFLAGS=${CXXFLAGS:--O2 -pipe}
export LDFLAGS="-static -L$STAGE/usr/lib -L$STAGE/usr/lib64 ${LDFLAGS:-}"
export CPPFLAGS="-I$STAGE/usr/include ${CPPFLAGS:-}"
export PKG_CONFIG_PATH="$STAGE/usr/lib/pkgconfig:$STAGE/usr/lib64/pkgconfig:${PKG_CONFIG_PATH:-}"
export PKG_CONFIG_LIBDIR="$PKG_CONFIG_PATH"
export OPENSSL_STAGE=${OPENSSL_STAGE:-$STAGE/usr}
export MAKEFLAGS=${MAKEFLAGS:--j$JOBS}
# Some GNU packages try to rebuild info pages; the runner may lack makeinfo.
export MAKEINFO=${MAKEINFO:-true}
export SOURCE_DATE_EPOCH=${SOURCE_DATE_EPOCH:-$(date +%s)}
export LC_ALL=C

mkdir -p "$PKGDEST" "$STAGE" "$BUILDDIR"

# --- helpers ---------------------------------------------------------------

strip_pkgdir() {
	local dir=$1 file magic
	[[ $STRIP_MODE == no ]] && return 0
	while IFS= read -r -d '' file; do
		[[ -L $file ]] && continue
		[[ -f $file ]] || continue
		magic=$(head -c 4 "$file" 2>/dev/null | od -An -tx1 | tr -d ' \n')
		[[ $magic == 7f454c46 ]] || continue
		"$STRIP" --strip-unneeded "$file" 2>/dev/null ||
			warn "strip failed: ${file#"$dir"/}"
	done < <(find "$dir" -type f -print0)
}

write_pkginfo() {
	local dir=$1
	local out=$dir/.PKGINFO
	local item
	{
		printf '# Generated by ci-build.sh from packages/%s/PKGBUILD\n' "$pkgname"
		printf 'pkgname = %s\n' "$pkgname"
		printf 'pkgver = %s\n' "$pkgver"
		printf 'pkgrel = %s\n' "$pkgrel"
		printf 'pkgdesc = %s\n' "${pkgdesc:-$pkgname}"
		printf 'url = %s\n' "${url:-}"
		printf 'builddate = %s\n' "$(date +%s)"
		printf 'packager = nterminal <d0m_1k@mail.ru>\n'
		printf 'size = 0\n'
		printf 'arch = aarch64\n'
		for item in "${license[@]:-}"; do
			[[ -n $item ]] && printf 'license = %s\n' "$item"
		done
		for item in "${depends[@]:-}"; do
			[[ -n $item ]] && printf 'depend = %s\n' "$item"
		done
		for item in "${provides[@]:-}"; do
			[[ -n $item ]] && printf 'provides = %s\n' "$item"
		done
		for item in "${conflicts[@]:-}"; do
			[[ -n $item ]] && printf 'conflicts = %s\n' "$item"
		done
		for item in "${replaces[@]:-}"; do
			[[ -n $item ]] && printf 'replaces = %s\n' "$item"
		done
	} > "$out"
	return 0
}

build_one() {
	local name=$1
	local pkgbuild=$ROOT/packages/$name/PKGBUILD
	[[ -f $pkgbuild ]] || die "no such package: $name ($pkgbuild)"

	local work=$BUILDDIR/$name
	rm -rf "$work"
	mkdir -p "$work/src" "$work/pkg"

	info "$name"

	(
		set -euo pipefail
		srcdir=$work/src
		pkgdir=$work/pkg
		cd "$srcdir"

		# shellcheck disable=SC1090
		source "$pkgbuild"

		[[ ${pkgname:-} == "$name" ]] ||
			die "$pkgbuild: pkgname '$pkgname' does not match directory '$name'"

		# --- sources ---
		local i url fn expected
		if declare -p source >/dev/null 2>&1; then
			for i in "${!source[@]}"; do
				url=${source[$i]}
				if [[ $url == *::* ]]; then
					fn=${url%%::*}
					url=${url#*::}
				else
					fn=${url##*/}
				fi
				if [[ ! -f $srcdir/$fn ]]; then
					printf '  -> %s\n' "$url"
					curl -fsSL --retry 3 --retry-delay 2 -o "$srcdir/$fn.part" "$url"
					mv -f "$srcdir/$fn.part" "$srcdir/$fn"
				fi
				expected=${sha256sums[$i]:-SKIP}
				if [[ $expected != SKIP ]]; then
					printf '%s  %s\n' "$expected" "$fn" |
						(cd "$srcdir" && sha256sum -c - >/dev/null) ||
						die "sha256 mismatch: $fn"
				fi
				case $fn in
					*.tar.gz|*.tgz|*.tar.xz|*.tar.bz2|*.tar.zst|*.tar)
						tar -xf "$srcdir/$fn" -C "$srcdir" ;;
					*.zip)
						unzip -q "$srcdir/$fn" -d "$srcdir" ;;
				esac
			done
		fi

		# --- build hooks ---
		local hook
		for hook in prepare build check package; do
			declare -F "$hook" >/dev/null || continue
			printf '  -> %s()\n' "$hook"
			(cd "$srcdir" && "$hook")
		done

		[[ -n $(ls -A "$pkgdir") ]] || die "package() produced no files"

		strip_pkgdir "$pkgdir"
		write_pkginfo "$pkgdir"

		"$ROOT/build-pkg.sh" "$pkgdir" "$PKGDEST"

		# Stage the installed tree for packages that link against it.
		(
			cd "$pkgdir"
			tar -cf - --exclude=.PKGINFO --exclude=.INSTALL --exclude=.BUILDINFO .
		) | (cd "$STAGE" && tar -xf -)
	)
}

for pkg in "${packages[@]}"; do
	build_one "$pkg"
done

info "done"
ls -l "$PKGDEST"/*.pkg.tar.zst 2>/dev/null || true
